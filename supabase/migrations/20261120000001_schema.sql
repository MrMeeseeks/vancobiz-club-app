create schema if not exists private;
revoke all on schema private from public;

-- ---------------------------------------------------------------------------
-- Categories (bilingual lookup, used by the directory filter and the flow report)
-- ---------------------------------------------------------------------------
create table public.categories (
  id       integer generated by default as identity primary key,
  slug     text not null unique,
  name_en  text not null,
  name_fa  text not null,
  sort     integer not null default 0
);

-- ---------------------------------------------------------------------------
-- Members: the PUBLIC profile of each business. Nothing private lives here.
-- ---------------------------------------------------------------------------
create table public.members (
  id                uuid primary key default gen_random_uuid(),
  member_number     integer not null unique check (member_number > 0),
  full_name         text not null check (char_length(full_name) between 1 and 120),
  full_name_fa      text check (char_length(full_name_fa) <= 120),
  business_name     text not null check (char_length(business_name) between 1 and 160),
  business_name_fa  text check (char_length(business_name_fa) <= 160),
  category_id       integer references public.categories (id) on delete set null,
  bio_en            text check (char_length(bio_en) <= 600),
  bio_fa            text check (char_length(bio_fa) <= 600),
  logo_url          text check (char_length(logo_url) <= 500),
  public_email      text check (char_length(public_email) <= 200),
  phone             text check (char_length(phone) <= 40),
  website           text check (char_length(website) <= 300),
  status            text not null default 'active' check (status in ('active', 'inactive')),
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Member accounts: who may log in, and with what role. Never public.
-- A login is matched to an account by its (confirmed) email address.
-- member_id is null only for an admin who is not a listed member (e.g. the builder).
-- ---------------------------------------------------------------------------
create table public.member_accounts (
  id           uuid primary key default gen_random_uuid(),
  login_email  text not null unique check (login_email = lower(btrim(login_email)) and char_length(login_email) between 3 and 200),
  role         text not null default 'member' check (role in ('member', 'admin')),
  member_id    uuid unique references public.members (id) on delete cascade,
  created_at   timestamptz not null default now(),
  constraint account_needs_member_unless_admin check (member_id is not null or role = 'admin')
);

-- ---------------------------------------------------------------------------
-- Referrals. Holds a third party's personal info: keep it minimal.
-- Only first name, one contact, a short need and optional notes.
-- ---------------------------------------------------------------------------
create table public.referrals (
  id                  uuid primary key default gen_random_uuid(),
  sender_id           uuid not null,
  receiver_id         uuid not null,
  client_first_name   text not null check (char_length(client_first_name) between 1 and 60),
  client_contact      text not null check (char_length(client_contact) between 3 and 120),
  need                text not null check (char_length(need) between 1 and 280),
  notes               text check (char_length(notes) <= 500),
  consent_confirmed   boolean not null check (consent_confirmed),   -- must be true
  consent_at          timestamptz not null default now(),
  status              text not null default 'pending'
                        check (status in ('pending', 'accepted', 'declined', 'contacted', 'won', 'lost')),
  deal_value_cad      numeric(12, 2) check (deal_value_cad >= 0),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  responded_at        timestamptz,          -- accepted or declined
  closed_at           timestamptz,          -- declined, won or lost
  client_redacted_at  timestamptz,          -- client data removed on request
  constraint referrals_sender_id_fkey   foreign key (sender_id)   references public.members (id) on delete restrict,
  constraint referrals_receiver_id_fkey foreign key (receiver_id) references public.members (id) on delete restrict,
  constraint referral_not_to_self check (sender_id <> receiver_id),
  constraint deal_value_only_when_won check (deal_value_cad is null or status = 'won')
);
create index referrals_sender_idx   on public.referrals (sender_id, created_at desc);
create index referrals_receiver_idx on public.referrals (receiver_id, created_at desc);
create index referrals_created_idx  on public.referrals (created_at);

-- Audit trail of every status change (for reports and the future API).
create table public.referral_events (
  id               bigint generated always as identity primary key,
  referral_id      uuid not null references public.referrals (id) on delete cascade,
  actor_member_id  uuid references public.members (id) on delete set null,
  from_status      text,
  to_status        text not null,
  created_at       timestamptz not null default now()
);
create index referral_events_referral_idx on public.referral_events (referral_id);

-- In-app notifications (new referral received, thank-you when a referral is won).
create table public.notifications (
  id           bigint generated always as identity primary key,
  member_id    uuid not null references public.members (id) on delete cascade,
  kind         text not null check (kind in ('referral_received', 'referral_won')),
  referral_id  uuid references public.referrals (id) on delete cascade,
  read_at      timestamptz,
  created_at   timestamptz not null default now()
);
create index notifications_member_idx on public.notifications (member_id, created_at desc);

-- "Join the Club" requests from the public form.
create table public.join_requests (
  id             uuid primary key default gen_random_uuid(),
  business_name  text not null check (char_length(business_name) between 1 and 160),
  contact_name   text not null check (char_length(contact_name) between 1 and 120),
  category_text  text check (char_length(category_text) <= 160),
  email          text not null check (char_length(email) between 3 and 200),
  phone          text check (char_length(phone) <= 40),
  reason         text check (char_length(reason) <= 1000),
  status         text not null default 'new' check (status in ('new', 'approved', 'rejected')),
  created_at     timestamptz not null default now(),
  reviewed_at    timestamptz
);

